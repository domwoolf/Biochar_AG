"""Build a flat LaTeX submission folder (submission/) from the rendered BiomassTEA.tex.

Submission systems place all uploaded files in one directory, so every \\includegraphics path is
reduced to its file name and the graphics (figures and RSC header/footer PDFs) are copied alongside
the .tex. The bibliography (references.bib, rsc.bst) is copied and BiomassTEA.bbl is generated by a
test compilation, which also checks that the folder is self-contained. Run after
`quarto render BiomassTEA.qmd --to ees-pdf` (which writes BiomassTEA.tex, keep-tex: true).
"""
import os
import re
import shutil
import subprocess
import sys

SRC = "BiomassTEA.tex"
OUT = "submission"
GRAPHICS_DIRS = ["", "_extensions/ees/head_foot/"]
EXTS = ["", ".pdf", ".png", ".jpg"]


def resolve(p):
    for d in GRAPHICS_DIRS:
        for ext in EXTS:
            f = os.path.join(d, p + ext)
            if os.path.isfile(f):
                return f
    return None


def main():
    tex = open(SRC, encoding="utf-8").read()
    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    os.makedirs(OUT)

    paths = re.findall(r"\\includegraphics(?:\[[^\]]*\])?\{([^}]*)\}", tex)
    copied = {}
    for p in paths:
        f = resolve(p)
        if f is None:
            sys.exit(f"make-submission: graphic not found: {p}")
        name = os.path.basename(f)
        if name in copied and copied[name] != f:
            sys.exit(f"make-submission: two graphics share the file name {name}")
        copied[name] = f
        shutil.copy(f, OUT)
        tex = tex.replace("{" + p + "}", "{" + os.path.basename(p) + "}")
    tex = re.sub(r"\\graphicspath\{\{_extensions/ees/head_foot/\}\}\n", "", tex)
    open(os.path.join(OUT, SRC), "w", encoding="utf-8").write(tex)
    for f in ("references.bib", "rsc.bst"):
        shutil.copy(f, OUT)

    # Test compilation: generates the .bbl and confirms nothing is missing
    stem = SRC[:-4]
    run = lambda *cmd: subprocess.run(cmd, cwd=OUT, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    run("pdflatex", "-interaction=nonstopmode", stem)
    run("bibtex", stem)
    run("pdflatex", "-interaction=nonstopmode", stem)
    run("pdflatex", "-interaction=nonstopmode", stem)
    log = open(os.path.join(OUT, stem + ".log"), encoding="latin-1").read()
    problems = re.findall(r"^!.*|.*not found.*|LaTeX Warning: (?:Reference|Citation).*undefined.*", log, re.M)
    pages = re.search(r"Output written on .*\((\d+) pages", log)
    for ext in (".aux", ".log", ".blg", ".out", ".pdf", ".toc", ".lof", ".lot"):
        f = os.path.join(OUT, stem + ext)
        if os.path.exists(f):
            os.remove(f)
    print(f"make-submission: {OUT}/ with {len(copied)} graphics; test build "
          f"{pages.group(1) + ' pages' if pages else 'FAILED'}; {len(problems)} problems")
    for p in sorted(set(problems)):
        print("  " + p)


if __name__ == "__main__":
    main()
